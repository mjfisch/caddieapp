#!/usr/bin/env node
// Generates src/rounds.generated.ts: every data/rounds/*.json embedded as a
// string, in filename order — the D22 round-sync mirror of
// generate-migrations-manifest.mjs (Mission 2.6). The runtime sync
// (src/roundSync.ts) imports that module instead of globbing the filesystem,
// so discovery works inside the Vercel serverless bundle where the raw .json
// files sit at no predictable path.
//
// Fail-loud discipline (D22): a missing/unreadable data/rounds directory, zero
// payload files, or a file that does not parse as JSON THROWS here, at build —
// discovery failure is never a silent skip.
//
// Runs automatically before `next build` (apps/web "prebuild"). The output is
// checked in so dev/tests need no build step; tests/rounds-manifest.test.ts
// fails if it goes stale.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";
import { dirname, join } from "node:path";

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));
export const ROUNDS_DIR = join(SCRIPT_DIR, "..", "..", "..", "data", "rounds");
export const ROUNDS_MANIFEST_PATH = join(SCRIPT_DIR, "..", "src", "rounds.generated.ts");

/** Build the full TypeScript source of the manifest module. Deterministic. */
export function generateRoundsManifestSource() {
  let files;
  try {
    files = readdirSync(ROUNDS_DIR)
      .filter((f) => f.endsWith(".json"))
      .sort(); // filename order === date order (YYYY-MM-DD_slug.json)
  } catch (err) {
    throw new Error(
      `data/rounds is missing or unreadable at ${ROUNDS_DIR}: ${err instanceof Error ? err.message : String(err)}`,
    );
  }
  if (files.length === 0) {
    throw new Error(`no .json round payloads found in ${ROUNDS_DIR}`);
  }
  const entries = files.map((filename) => {
    const json = readFileSync(join(ROUNDS_DIR, filename), "utf8");
    try {
      JSON.parse(json);
    } catch (err) {
      throw new Error(
        `round payload ${filename} is not valid JSON: ${err instanceof Error ? err.message : String(err)}`,
      );
    }
    return `  {\n    filename: ${JSON.stringify(filename)},\n    json: ${JSON.stringify(json)},\n  },`;
  });
  return [
    "// AUTO-GENERATED by services/api/scripts/generate-rounds-manifest.mjs — DO NOT EDIT.",
    "// Regenerate with: node services/api/scripts/generate-rounds-manifest.mjs",
    "// (also runs automatically as the apps/web prebuild step).",
    "//",
    "// Embeds every data/rounds/*.json as a string so the D22 round sync in",
    "// roundSync.ts never reads the filesystem at runtime — same bundle-safety",
    "// rationale as migrations.generated.ts (docs/diagnostic_migration_009.md).",
    "",
    "export interface RoundFile {",
    "  readonly filename: string;",
    "  readonly json: string;",
    "}",
    "",
    "export const ROUND_FILES: readonly RoundFile[] = [",
    ...entries,
    "];",
    "",
  ].join("\n");
}

// Write the manifest when executed directly (not when imported by tests).
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const source = generateRoundsManifestSource();
  writeFileSync(ROUNDS_MANIFEST_PATH, source);
  const count = (source.match(/filename: "/g) ?? []).length;
  console.log(`[rounds-manifest] wrote ${ROUNDS_MANIFEST_PATH} (${count} rounds)`);
}
