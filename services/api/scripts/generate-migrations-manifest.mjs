#!/usr/bin/env node
// Generates src/migrations.generated.ts: every src/migrations/*.sql embedded as a
// string, in filename order. The migration runner (src/db.ts) imports that module
// instead of reading the filesystem, so discovery works inside the Vercel
// serverless bundle where the raw .sql files may not exist at any predictable path.
//
// Runs automatically before `next build` (apps/web "prebuild"). The output is
// checked in so dev/tests need no build step; tests/migration-manifest.test.ts
// fails if it goes stale.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";
import { dirname, join } from "node:path";

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));
export const MIGRATIONS_DIR = join(SCRIPT_DIR, "..", "src", "migrations");
export const MANIFEST_PATH = join(SCRIPT_DIR, "..", "src", "migrations.generated.ts");

/** Build the full TypeScript source of the manifest module. Deterministic. */
export function generateManifestSource() {
  const files = readdirSync(MIGRATIONS_DIR)
    .filter((f) => f.endsWith(".sql"))
    .sort(); // filename order: 001_… before 002_…
  if (files.length === 0) {
    throw new Error(`no .sql migrations found in ${MIGRATIONS_DIR}`);
  }
  const entries = files.map((filename) => {
    const sql = readFileSync(join(MIGRATIONS_DIR, filename), "utf8");
    return `  {\n    filename: ${JSON.stringify(filename)},\n    sql: ${JSON.stringify(sql)},\n  },`;
  });
  return [
    "// AUTO-GENERATED by services/api/scripts/generate-migrations-manifest.mjs — DO NOT EDIT.",
    "// Regenerate with: node services/api/scripts/generate-migrations-manifest.mjs",
    "// (also runs automatically as the apps/web prebuild step).",
    "//",
    "// Embeds every services/api/src/migrations/*.sql as a string so the runner in",
    "// db.ts never reads the filesystem at runtime — the silent ENOENT skip inside",
    "// the Vercel bundle (see docs/diagnostic_migration_009.md) cannot recur.",
    "",
    "export interface MigrationFile {",
    "  readonly filename: string;",
    "  readonly sql: string;",
    "}",
    "",
    "export const MIGRATIONS: readonly MigrationFile[] = [",
    ...entries,
    "];",
    "",
  ].join("\n");
}

// Write the manifest when executed directly (not when imported by tests).
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const source = generateManifestSource();
  writeFileSync(MANIFEST_PATH, source);
  const count = (source.match(/filename: "/g) ?? []).length;
  console.log(`[migrations-manifest] wrote ${MANIFEST_PATH} (${count} migrations)`);
}
